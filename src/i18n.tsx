interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: keyof (typeof messages)["en"], params?: Params) => string;
  fieldTypeLabel: (type: FieldType) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const fieldTypeKeys: Record<FieldType, keyof (typeof messages)["en"]> = {
  shortText: "fieldTypeShortText",
  longText: "fieldTypeLongText",
  dropdown: "fieldTypeDropdown",
  checkbox: "fieldTypeCheckbox",
  rating: "fieldTypeRating",
  url: "fieldTypeUrl",
  screenshot: "fieldTypeScreenshot",
  video: "fieldTypeVideo",
};

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "ja") {
      setLanguage(stored);
    }
  }, []);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    function t(key: keyof (typeof messages)["en"], params?: Params) {
      const message = messages[language][key];
      return typeof message === "function" ? message(params) : message;
    }

    return {
      language,
      setLanguage,
      t,
      fieldTypeLabel(type) {
        return t(fieldTypeKeys[type]);
      },
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return value;
}

